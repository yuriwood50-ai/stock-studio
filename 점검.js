// 투명 캔버스 가운데에 불투명 네모 하나를 그려 PNG로 낸다
async function 시험그림(파일이름, 캔버스가로, 캔버스세로, 네모가로, 네모세로) {
  fsm.mkdirSync(그림둘곳, { recursive: true });
  const 그림 = new 짐프({ width: 캔버스가로, height: 캔버스세로, color: 0x00000000 });
  const x0 = Math.floor((캔버스가로 - 네모가로) / 2);
  const y0 = Math.floor((캔버스세로 - 네모세로) / 2);
  for (let y = y0; y < y0 + 네모세로; y += 1) {
    for (let x = x0; x < x0 + 네모가로; x += 1) 그림.setPixelColor(0x8b5a2bff, x, y);
  }
  const 길 = pathm.join(그림둘곳, 파일이름);
  await 그림.write(길);
  return 길;
}

