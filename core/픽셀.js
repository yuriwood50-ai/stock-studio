// 비트맵을 다루는 손 (계획서 7장)
//
// 비트맵은 {width, height, data} 이고 data는 RGBA 한 픽셀에 4바이트다.
// jimp의 .bitmap 과 같은 모양이라 그대로 주고받는다.
//
// jimp의 autocrop()은 색 유사도 기준이고 "네 변 모두에 여백이 있을 때만" 자른다.
// 이 문서의 크롭 규칙과 달라서 알파 스캔을 직접 짠다 (계획서 2장).

function 알파(비트맵, x, y) {
  return 비트맵.data[(y * 비트맵.width + x) * 4 + 3];
}

/** 알파 임계값 이상인 픽셀이 하나라도 있나 — 7장 1번 */
function 오브젝트가있나(비트맵, 임계) {
  const 데이터 = 비트맵.data;
  for (let 자리 = 3; 자리 < 데이터.length; 자리 += 4) {
    if (데이터[자리] >= 임계) return true;
  }
  return false;
}

/** 알파 임계값 미만인 픽셀이 하나라도 있나 — 7장 2번 */
function 투명한데가있나(비트맵, 임계) {
  const 데이터 = 비트맵.data;
  for (let 자리 = 3; 자리 < 데이터.length; 자리 += 4) {
    if (데이터[자리] < 임계) return true;
  }
  return false;
}

/** 네 변에 알파 임계값 이상이 닿았나 — 7장 3번 (잘린 이미지) */
function 가장자리에닿나(비트맵, 임계) {
  const { width: 가로, height: 세로 } = 비트맵;

  for (let x = 0; x < 가로; x += 1) {
    if (알파(비트맵, x, 0) >= 임계) return true;
    if (알파(비트맵, x, 세로 - 1) >= 임계) return true;
  }
  for (let y = 0; y < 세로; y += 1) {
    if (알파(비트맵, 0, y) >= 임계) return true;
    if (알파(비트맵, 가로 - 1, y) >= 임계) return true;
  }
  return false;
}

/** 오브젝트가 차지한 네모 — 없으면 null */
function 오브젝트범위(비트맵, 임계) {
  const { width: 가로, height: 세로 } = 비트맵;
  let 왼 = Infinity;
  let 위 = Infinity;
  let 오른 = -1;
  let 아래 = -1;

  for (let y = 0; y < 세로; y += 1) {
    for (let x = 0; x < 가로; x += 1) {
      if (알파(비트맵, x, y) < 임계) continue;
      if (x < 왼) 왼 = x;
      if (x > 오른) 오른 = x;
      if (y < 위) 위 = y;
      if (y > 아래) 아래 = y;
    }
  }

  if (오른 < 0) return null;
  return { 왼, 위, 오른, 아래, 가로: 오른 - 왼 + 1, 세로: 아래 - 위 + 1 };
}

/** 빈 비트맵 (전부 투명) */
function 빈비트맵(가로, 세로) {
  return { width: 가로, height: 세로, data: Buffer.alloc(가로 * 세로 * 4, 0) };
}

/** 원본의 (왼, 위)에서 시작하는 네모를 새 비트맵에 옮겨 담는다. 밖은 투명으로 둔다 */
function 옮겨담기(원본, 왼, 위, 새가로, 새세로) {
  const 새것 = 빈비트맵(새가로, 새세로);
  const { width: 가로, height: 세로, data: 원본데이터 } = 원본;

  for (let j = 0; j < 새세로; j += 1) {
    const 원y = 위 + j;
    if (원y < 0 || 원y >= 세로) continue;

    for (let i = 0; i < 새가로; i += 1) {
      const 원x = 왼 + i;
      if (원x < 0 || 원x >= 가로) continue;

      const 온데 = (원y * 가로 + 원x) * 4;
      const 갈데 = (j * 새가로 + i) * 4;
      새것.data[갈데] = 원본데이터[온데];
      새것.data[갈데 + 1] = 원본데이터[온데 + 1];
      새것.data[갈데 + 2] = 원본데이터[온데 + 2];
      새것.data[갈데 + 3] = 원본데이터[온데 + 3];
    }
  }

  return 새것;
}

/**
 * ① 알파 경계로 타이트하게 자른다 — 여백을 붙이지 않는다 (7장 8번)
 *
 * 결과는 오브젝트 경계 상자와 정확히 같은 크기다.
 * 여백을 붙이는 것은 기본여백덧대기가 따로 맡는다.
 */
function 타이트하게자르기(비트맵, 범위) {
  return 옮겨담기(비트맵, 범위.왼, 범위.위, 범위.가로, 범위.세로);
}

/**
 * ② 사방에 기본 픽셀 여백을 덧댄다 — 7장 10번
 *
 * 타이트 크롭한 것을 받아 네 변에 같은 폭의 투명 여백을 붙인다.
 * 옮겨담기가 원본 밖을 투명으로 두므로 덧대기가 한 줄로 끝난다.
 *
 * 덧대기를 없앤 뒤로 이것이 마지막 크기 변경이다. 여기서 최종 크기가 정해진다.
 */
function 기본여백덧대기(비트맵, 여백) {
  if (!여백) return 비트맵;
  return 옮겨담기(
    비트맵,
    -여백,
    -여백,
    비트맵.width + 여백 * 2,
    비트맵.height + 여백 * 2
  );
}

/**
 * ①+② 를 이어서 한다 — 부르는 쪽이 편하라고 둔 이음매다.
 *
 * 검사.js는 축소를 사이에 끼워야 해서 두 함수를 따로 부른다 (7장 9번).
 */
function 잘라내기(비트맵, 범위, 여백) {
  return 기본여백덧대기(타이트하게자르기(비트맵, 범위), 여백);
}

/**
 * 오브젝트 자체가 가질 수 있는 가장 긴 축 — 7장 9번
 *
 * 오브젝트 + 양쪽 기본 여백이 최대 긴 축을 넘으면 안 된다.
 * 그래서 축소 목표는 여백을 뺀 값이다. 여백 12px이면 9800 - 12 - 12 = 9776.
 *
 * 이 값으로 줄이면 여백을 붙인 뒤에도 최대 긴 축을 정확히 맞춘다.
 */
function 최대오브젝트긴축(최대긴축px, 여백px) {
  return 최대긴축px - 여백px * 2;
}

// 짧은축 덧대기는 없앴다 (7장 · 0장 개정표).
//
// 어도비 4MP 하한만 보고 만든 규칙이었는데, 미리캔버스는 여백 규격이 엄격해서
// 세로로 긴 이미지에 투명 여백을 많이 넣으면 오히려 미승인 사유가 됐다.
// 지금은 덧대지 않고 그대로 두고, 어디에 올릴 수 있는지 판정만 한다 (7장 10번).

/**
 * 32×32 회색조 지문 — 7장 유사도 판정
 *
 * 투명한 곳은 흰 바탕에 얹어 본다. 눈으로 보는 것과 같게 하기 위해서다.
 * (계획서는 "회색조 변환"이라고만 해서 알파를 어떻게 볼지는 여기서 정했다)
 */
const 지문한변 = 32;

function 지문만들기(비트맵) {
  const { width: 가로, height: 세로, data: 데이터 } = 비트맵;
  const 지문 = new Float64Array(지문한변 * 지문한변);

  for (let 칸y = 0; 칸y < 지문한변; 칸y += 1) {
    const y시작 = Math.floor((칸y * 세로) / 지문한변);
    const y끝 = Math.max(y시작 + 1, Math.floor(((칸y + 1) * 세로) / 지문한변));

    for (let 칸x = 0; 칸x < 지문한변; 칸x += 1) {
      const x시작 = Math.floor((칸x * 가로) / 지문한변);
      const x끝 = Math.max(x시작 + 1, Math.floor(((칸x + 1) * 가로) / 지문한변));

      let 합 = 0;
      let 수 = 0;

      for (let y = y시작; y < y끝 && y < 세로; y += 1) {
        for (let x = x시작; x < x끝 && x < 가로; x += 1) {
          const 자리 = (y * 가로 + x) * 4;
          const 알파값 = 데이터[자리 + 3] / 255;
          const 빨 = 데이터[자리] * 알파값 + 255 * (1 - 알파값);
          const 초 = 데이터[자리 + 1] * 알파값 + 255 * (1 - 알파값);
          const 파 = 데이터[자리 + 2] * 알파값 + 255 * (1 - 알파값);
          합 += 0.299 * 빨 + 0.587 * 초 + 0.114 * 파;
          수 += 1;
        }
      }

      지문[칸y * 지문한변 + 칸x] = 수 ? 합 / 수 : 255;
    }
  }

  return 지문;
}

/** 두 지문의 픽셀별 절대차 평균 (0~255) */
function 지문차이(가, 나) {
  let 합 = 0;
  for (let 자리 = 0; 자리 < 가.length; 자리 += 1) {
    합 += Math.abs(가[자리] - 나[자리]);
  }
  return 합 / 가.length;
}

