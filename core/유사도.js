// 유사도 판정 (계획서 7장)
//
// - 각 이미지를 32×32 회색조로 줄인다 (픽셀.js 지문만들기)
// - 세트 안 모든 쌍을 비교해 픽셀 차이의 평균을 낸다
// - 차이가 기준값 아래면 두 장 다 표시 대상
// - 표시 방법: 파일 이름 뒤에 _check를 붙인다. 지우지 않는다

const { 지문차이 } = require('./픽셀');

/**
 * @param {Array<{지문: Float64Array}>} 통과한것들
 * @param {number} 기준값 0~255. 낮을수록 더 적게 표시된다
 * @returns {{표시할자리: Set<number>, 쌍들: Array}}
 */
function 닮은것찾기(통과한것들, 기준값) {
  const 표시할자리 = new Set();
  const 쌍들 = [];
  const 잰것 = [];

  // 기준값이 없어도 재기는 한다.
  // 13장은 잰 값을 보고 기준값을 정하라고 한다. 안 재면 정할 수가 없다.
  const 표시한다 = Number.isFinite(기준값);

  for (let 가 = 0; 가 < 통과한것들.length; 가 += 1) {
    for (let 나 = 가 + 1; 나 < 통과한것들.length; 나 += 1) {
      const 차이 = 지문차이(통과한것들[가].지문, 통과한것들[나].지문);
      잰것.push({ 가, 나, 차이 });

      if (표시한다 && 차이 < 기준값) {
        표시할자리.add(가);
        표시할자리.add(나);
        쌍들.push({ 가, 나, 차이 });
      }
    }
  }

  return { 표시할자리, 쌍들, 잰것 };
}

/** 기준값을 눈으로 정할 때 쓰는 요약 (13장) */
function 차이요약(잰것) {
  if (!잰것.length) return null;
  const 값들 = 잰것.map((하나) => 하나.차이).sort((가, 나) => 가 - 나);
  return {
    가장닮은쌍: 값들[0],
    가운데: 값들[Math.floor(값들.length / 2)],
    가장다른쌍: 값들[값들.length - 1],
    쌍수: 값들.length,
  };
}

module.exports = { 닮은것찾기, 차이요약 };
