// 통과 검사 (계획서 7장)
//
//    1  파일을 읽을 수 있는가                    → 못 읽으면 제외 (파일 못 읽음)
//    2  알파 26 이상인 픽셀이 있는가              → 없으면 제외 (빈 이미지)
//    3  알파 26 미만인 픽셀이 있는가              → 없으면 제외 (투명 배경 아님)
//    4  원본 4MP 이상 · 원본 짧은 축 700px 이상인가 → 아니면 제외 (이미지 크기 미달)
//    5  네 변에 알파 26 이상이 닿았나             → 닿았으면 제외 (잘림)
//    6  알파 26 기준 경계 상자를 재고 타이트 크롭
//    7  오브젝트 + 양쪽 여백이 9800px을 넘나        → 넘으면 오브젝트를 비율 유지 축소
//    8  사방에 기본 여백 12px을 덧댄다
//    9  최종 짧은 축 700px 이상인가                → 아니면 제외 (오브젝트가 작음)
//   10  최종 넓이 4MP 이상인가                     → 예: 양쪽 / 아니오: 미리캔버스만
//   11  PNG로 다시 저장한 용량이 45MB 이하인가      → 아니면 제외 (용량 초과)
//   12  sRGB 선언과 120dpi를 PNG 청크로 넣는다     (검사가 아니라 부여)
//   13  청크까지 넣은 최종 버퍼가 45MB 이하인가     → 아니면 제외 (용량 초과)
//   14  세트 안에서 서로 닮았나                    → 표시만 (유사도.js)
//
// 순서에서 중요한 네 가지
//   4번이 6번보다 먼저다 — 원본이 규격 미달인 것을 크롭·축소로 구제하지 않는다
//   5번이 6번보다 먼저다 — 크롭한 뒤에는 원래 잘려 있었는지 알 수 없다
//   7번이 8번보다 먼저다 — 오브젝트만 줄여야 축소 뒤에도 기본 여백이 설정값 그대로 남는다
//   10번은 제외가 아니라 갈림길이다 — 여기서 파일이 어디로 갈지 정해진다
//
// **덧대기와 3:1 검사는 없앴다** (0장 개정표).
//   덧대기 — 어도비 4MP 하한만 보고 만든 규칙인데, 미리캔버스는 여백 규격이
//            엄격해서 세로로 긴 이미지에 투명 여백을 많이 넣으면 오히려
//            미승인 사유가 됐다. 이제 덧대지 않고 갈 곳만 판정한다 (10번).
//   3:1    — 덧대기가 사라져 비율을 인위적으로 만들 일이 없고,
//            API가 생성 단계에서 이미 3:1로 막는다 (5-2장).
//
// 오브젝트 점유율은 이 순서에 없다. 판정에 쓰지 않는 관찰값이다 (5-2장 · 13장).

const fs = require('fs');
const { Jimp, JimpMime } = require('jimp');

const 픽셀 = require('./픽셀');
const 설정모듈 = require('./설정');
const { 색공간과해상도넣기 } = require('./png청크');

// 제외 사유는 이 일곱 가지뿐이다. 다른 문구를 만들지 않는다 (7장)
const 사유 = {
  빈이미지: '빈 이미지',
  투명아님: '투명 배경 아님',
  크기미달: '이미지 크기 미달',
  잘림: '잘림',
  작음: '오브젝트가 작음',
  용량: '용량 초과',
  못읽음: '파일 못 읽음',
};

function 제외(까닭, 덧붙임) {
  return { 통과: false, 사유: 까닭, 덧붙임: 덧붙임 || '' };
}

/**
 * 한 장을 검사하고 고친다.
 *
 * @param {string} 경로   손으로 넣은 원본
 * @param {object} 설정
 * @returns {Promise<object>}
 *   통과      true면 결과 폴더에 담는다
 *   사유      통과가 false일 때만
 *   버퍼      저장할 PNG (sRGB · dpi 청크까지 들어간 것)
 *   가로 세로 최종 크기
 *   지문      유사도 비교용 32×32
 *   고친것    사람에게 보여줄 처리 내역
 */
async function 한장검사(경로, 설정) {
  const 임계 = 설정.알파임계값;
  const 여백 = 설정.여백px;
  const 고침 = [];

  // 1 — 파일을 읽을 수 있나
  let 그림;
  try {
    그림 = await Jimp.read(경로);
  } catch {
    return 제외(사유.못읽음);
  }

  let 비트맵 = 그림.bitmap;
  if (!비트맵 || !비트맵.width || !비트맵.height) return 제외(사유.못읽음);

  // 2 — 그릴 게 있나
  if (!픽셀.오브젝트가있나(비트맵, 임계)) return 제외(사유.빈이미지);

  // 3 — 배경이 투명한가
  if (!픽셀.투명한데가있나(비트맵, 임계)) return 제외(사유.투명아님);

  // 4 — 원본 캔버스가 규격을 채우나. 크롭·축소·덧대기보다 먼저 본다
  //
  // 여기서 걸린 것은 고치지 않는다. 저해상도 원본에 투명 여백을 덧대 4MP를
  // 만들면 픽셀은 늘지 않으면서 규격만 속이게 된다. 오브젝트를 확대하는 것도
  // 흐릿해질 뿐이라 하지 않는다. 다시 뽑는 것이 맞다.
  const 원본가로 = 비트맵.width;
  const 원본세로 = 비트맵.height;
  const 원본넓이 = 원본가로 * 원본세로;
  const 원본짧은축 = Math.min(원본가로, 원본세로);
  const 최소넓이 = 설정.고정.최소크기MP * 1_000_000;

  if (원본넓이 < 최소넓이 || 원본짧은축 < 설정.고정.최소짧은축px) {
    const 무엇이 =
      원본넓이 < 최소넓이
        ? `최소 ${설정.고정.최소크기MP}MP`
        : `최소 짧은 축 ${설정.고정.최소짧은축px}px`;
    return 제외(
      사유.크기미달,
      `원본 ${원본가로}×${원본세로} · ${(원본넓이 / 1_000_000).toFixed(2)}MP · ${무엇이}`
    );
  }

  // 5 — 잘리지 않았나. 크롭보다 먼저 봐야 한다
  if (픽셀.가장자리에닿나(비트맵, 임계)) return 제외(사유.잘림);

  // 6 — 알파 경계 상자를 재고 타이트 크롭. 여백은 아직 붙이지 않는다
  const 범위 = 픽셀.오브젝트범위(비트맵, 임계);

  // 오브젝트가 캔버스에서 얼마나 차지했나 — 5장 문장을 확인하는 관찰값이다.
  // 판정에는 쓰지 않는다 (5-2장 · 13장)
  const 점유율 = Math.max(범위.가로, 범위.세로) / Math.max(원본가로, 원본세로);

  const 크롭전 = `${원본가로}×${원본세로}`;
  비트맵 = 픽셀.타이트하게자르기(비트맵, 범위);

  // 7 — 오브젝트 + 양쪽 여백이 긴 축 상한을 넘으면 오브젝트만 줄인다.
  //
  // 여백을 붙이기 전에 줄여야 축소 뒤에도 기본 여백이 설정값 그대로 남는다.
  // 2880 캔버스에서는 걸리지 않지만 생성 크기를 바꾸면 걸린다
  const 오브젝트상한 = 픽셀.최대오브젝트긴축(설정.고정.최대긴축px, 여백);
  const 지금오브젝트긴축 = Math.max(비트맵.width, 비트맵.height);
  if (지금오브젝트긴축 > 오브젝트상한) {
    const 배율 = 오브젝트상한 / 지금오브젝트긴축;
    const 줄인그림 = new Jimp({ width: 1, height: 1, color: 0x00000000 });
    줄인그림.bitmap = 비트맵;
    줄인그림.resize({
      w: Math.max(1, Math.round(비트맵.width * 배율)),
      h: Math.max(1, Math.round(비트맵.height * 배율)),
    });
    비트맵 = 줄인그림.bitmap;
    고침.push(
      `줄임 → ${비트맵.width}×${비트맵.height} (오브젝트 상한 ${오브젝트상한}px)`
    );
  }

  // 8 — 사방에 기본 픽셀 여백. 여기서 최종 크기가 정해진다.
  // 덧대기가 없어졌으므로 이 뒤로 크기는 더 바뀌지 않는다
  비트맵 = 픽셀.기본여백덧대기(비트맵, 여백);
  고침.push(`잘라냄 ${크롭전} → ${비트맵.width}×${비트맵.height} (여백 ${여백}px)`);

  const 최종짧은축 = Math.min(비트맵.width, 비트맵.height);
  const 최종넓이 = 비트맵.width * 비트맵.height;

  // 9 — 짧은 축이 700px에 못 미치면 어디에도 못 올린다. 이때만 제외다
  if (최종짧은축 < 설정.고정.최소짧은축px) {
    return 제외(
      사유.작음,
      `크롭 후 ${비트맵.width}×${비트맵.height} · 짧은 축 ${최종짧은축}px · ` +
        `최소 ${설정.고정.최소짧은축px}px`
    );
  }

  // 10 — 갈림길. 4MP를 넘으면 양쪽에, 못 넘으면 미리캔버스에만 올린다.
  //
  // 앞 판은 여기서 투명 여백을 덧대 4MP를 억지로 맞췄다. 그러면 어도비는
  // 통과해도 미리캔버스 여백 규격에 걸린다. 고치지 않고 사실을 남긴다.
  // 어도비에도 올리고 싶으면 대각선 구도로 다시 그리는 것이 답이다 (7장).
  const 어디에 =
    최종넓이 >= 최소넓이 ? 설정모듈.플랫폼.양쪽 : 설정모듈.플랫폼.미리캔버스;

  // 11 — PNG로 다시 저장한 용량
  const 낼그림 = new Jimp({ width: 1, height: 1, color: 0x00000000 });
  낼그림.bitmap = 비트맵;
  let 버퍼;
  try {
    버퍼 = await 낼그림.getBuffer(JimpMime.png);
  } catch (오류) {
    return 제외(사유.못읽음, 오류.message);
  }

  const 저장직후메가 = 버퍼.length / (1024 * 1024);
  if (저장직후메가 > 설정.고정.최대용량MB) {
    return 제외(사유.용량, `${저장직후메가.toFixed(1)}MB`);
  }

  // 12 — sRGB와 120dpi를 청크로 넣는다 (검사가 아니라 부여)
  try {
    버퍼 = 색공간과해상도넣기(버퍼, 설정.고정.해상도dpi);
  } catch (오류) {
    return 제외(사유.못읽음, 오류.message);
  }
  고침.push(`sRGB · ${설정.고정.해상도dpi}dpi 넣음`);

  // 13 — 청크가 들어가 조금 커졌다. 최종 버퍼로 다시 본다
  const 메가 = 버퍼.length / (1024 * 1024);
  if (메가 > 설정.고정.최대용량MB) {
    return 제외(사유.용량, `${메가.toFixed(1)}MB`);
  }

  return {
    통과: true,
    버퍼,
    가로: 비트맵.width,
    세로: 비트맵.height,
    넓이MP: (비트맵.width * 비트맵.height) / 1_000_000,
    용량MB: 메가,
    어디에, // '양쪽' 또는 '미리캔버스' (7장 10번)
    점유율,
    지문: 픽셀.지문만들기(비트맵),
    고친것: 고침,
  };
}

// 원본 크기만 알아보는 가벼운 읽기 (보고용)
async function 크기만(경로) {
  try {
    const 그림 = await Jimp.read(경로);
    return { 가로: 그림.bitmap.width, 세로: 그림.bitmap.height };
  } catch {
    return null;
  }
}

module.exports = { 한장검사, 크기만, 사유 };
