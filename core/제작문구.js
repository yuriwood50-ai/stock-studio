// 화면 3이 쓰는 문구 (계획서 6장)
//
// - 프롬프트 목록과 전체 복사
// - 파일받기 문구 — 파일명을 박아서 생성한다
//
// 파일명이 프롬프트·파일받기 문구·실제 저장 세 군데에 나오는데,
// 전부 이름.파일명() 하나에서 나와야 어긋나지 않는다.

const 이름 = require('./이름');
const 프롬프트 = require('./프롬프트');
const { 패턴유형 } = require('./설정');

/**
 * 목록에 아이템번호와 파일명, 프롬프트를 붙인다.
 * 세트만들기가 실제로 만들 이름과 같은 규칙을 쓴다 (8장).
 */
function 항목들만들기(세트번호, 목록, 그림체, 제출유형, 문장) {
  const 정리된소재명 = 이름.소재명들정리(목록.map((하나) => 하나.소재));
  const 확장자 = 제출유형 === 패턴유형 ? '.jpg' : '.png';

  return 목록.map((하나, 자리) => {
    const 아이템번호 = 이름.아이템번호(세트번호, 자리 + 1);
    const 항목 = {
      아이템번호,
      소재: String(하나.소재 || '').trim(),
      형태: String(하나.형태 || '').trim(),
      파일명: 이름.파일명(아이템번호, 정리된소재명[자리], 확장자),
    };
    항목.프롬프트 = 프롬프트.조립(항목, 그림체, 제출유형, 문장);
    return 항목;
  });
}

/**
 * 전체 복사 — 카드 사이에 구분선을 넣어 이어 붙인다 (6장)
 *
 *   ── 01 · O03-01_스테이플러.png ──
 *   (프롬프트)
 *
 *   ── 02 · O03-02_클립통.png ──
 *   (프롬프트)
 */
function 전체복사글(항목들) {
  return 항목들
    .map((항목, 자리) => {
      const 번호 = String(자리 + 1).padStart(2, '0');
      return `── ${번호} · ${항목.파일명} ──\n${항목.프롬프트}`;
    })
    .join('\n\n');
}

/**
 * 파일받기 문구 — 아래 틀에 실제 파일명을 채운다 (6장)
 *
 * JPG는 이번 범위에서 고를 수 없으므로 (3장) 투명 PNG 문구 하나만 만든다.
 */
function 파일받기문구(항목들, 여백px) {
  const 이름줄 = 항목들
    .map((항목, 자리) => `  ${자리 + 1}번째 → ${항목.파일명}`)
    .join('\n');

  return [
    '[모드: 파일화/다운로드]',
    '대상: 방금 생성 완료된 결과물만 사용합니다.',
    '목적: 업로드용 파일로 정리합니다.',
    '절대 금지: 새 이미지 생성, 재생성, 추가 변형, 재디자인,',
    '          색상·형태·질감 변경, 배경 새로 만들기, 텍스트/로고/워터마크 추가.',
    '작업: 실제 RGBA 알파값이 있는 투명 PNG로 처리,',
    '      체크무늬/흰 배경/회색 배경 박힘 금지,',
    `      오브젝트 기준 사방 여백 ${여백px}px, 잘림 없음, 원본 질감 유지.`,
    '아래 이름 그대로 붙여 주세요.',
    이름줄,
  ].join('\n');
}

module.exports = { 항목들만들기, 전체복사글, 파일받기문구 };
