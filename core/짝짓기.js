// 받은 파일과 소재 목록 짝짓기 (계획서 6장)
//
// 두 가지 일이 있고, 섞으면 안 된다.
//
//   전체  — 처음부터 다시 배정한다. 사람이 손으로 고친 것도 풀린다.
//           `짝 다시 맞추기` 단추를 눌렀을 때와 소재 목록이 바뀌었을 때만 한다.
//   추가  — 이미 지어진 짝은 그대로 두고, 이번에 새로 받은 파일만 빈 자리에 넣는다.
//           파일을 나눠 받을 때 쓴다 (6장 7번).
//
// 배정 규칙은 두 갈래다.
//   ① 파일명이 O03-01_... 형태면 그 번호의 빈 자리에 넣는다
//   ② 번호가 없는 파일만 이름 자연순으로 남은 빈 자리를 채운다
//
// 번호가 있는데 넣지 못한 파일(번호가 이미 찼거나 · 목록에 없거나 · 같은 번호가 겹침)은
// **남은 파일로 둔다.** 순서 배정으로 흘려보내면 사람이 붙인 번호를 프로그램이
// 무시하고 엉뚱한 소재에 갖다 붙이게 된다.

const path = require('path');

// 짝을 어떻게 지었는지. 이 셋 말고는 쓰지 않는다
const 허용방법 = ['파일명', '순서', '사람이'];

const 번호꼴 = /^([OP]\d{2}-\d{2})/i;

/** 파일 경로에서 아이템번호를 뽑는다. 없으면 null */
function 파일속번호(경로) {
  const 맞음 = path.basename(경로).match(번호꼴);
  return 맞음 ? 맞음[1].toUpperCase() : null;
}

/**
 * 이미 지어진 짝을 검증해 자리에 앉힌다 (13-3).
 *
 * 하나가 잘못됐다고 전체를 멈추지 않는다. 그 짝만 버리고 까닭을 경고에 남긴다.
 */
function 기존짝앉히기(짝, 번호자리, 기존짝, 경고) {
  const 쓴파일 = new Set();
  const 앉은번호 = new Set();

  for (const 하나 of 기존짝 || []) {
    const 번호 = String(하나 && 하나.아이템번호 ? 하나.아이템번호 : '').toUpperCase();
    const 파일 = 하나 && 하나.파일 ? 하나.파일 : null;
    const 방법 = 하나 && 하나.방법 ? 하나.방법 : null;

    if (!번호 || !파일) continue;

    const 자리 = 번호자리.get(번호);
    if (자리 === undefined) {
      경고.push(`${번호}은 지금 목록에 없어서 짝을 풀었어요.`);
      continue;
    }
    if (앉은번호.has(번호)) {
      경고.push(`${번호}에 짝이 두 번 들어와서 처음 것만 남겼어요.`);
      continue;
    }
    if (쓴파일.has(파일)) {
      경고.push(`${번호}이 다른 소재와 같은 파일을 가리켜서 짝을 풀었어요.`);
      continue;
    }
    if (!허용방법.includes(방법)) {
      경고.push(`${번호}의 짝지은 방법을 알 수 없어서 짝을 풀었어요.`);
      continue;
    }

    짝[자리].파일 = 파일;
    짝[자리].방법 = 방법;
    쓴파일.add(파일);
    앉은번호.add(번호);
  }

  return 쓴파일;
}

/**
 * 빈 자리에 파일을 배정한다 — ①번호 먼저, ②나머지는 자연순.
 *
 * 기존 짝이 앉아 있는 자리와 파일은 건드리지 않는다.
 */
function 빈자리채우기(짝, 번호자리, 배정할파일, 쓴파일) {
  const 남음 = [];
  const 번호없는것 = [];

  // ① 파일명에 아이템번호가 박힌 것부터
  for (const 경로 of 배정할파일) {
    if (쓴파일.has(경로)) continue;

    const 번호 = 파일속번호(경로);
    if (!번호) {
      번호없는것.push(경로);
      continue;
    }

    const 자리 = 번호자리.get(번호);

    // 번호가 목록에 없거나 · 그 자리가 이미 찼으면(같은 번호가 겹친 경우 포함)
    // 순서 배정으로 넘기지 않고 남은 파일로 둔다
    if (자리 === undefined || 짝[자리].파일) {
      남음.push(경로);
      continue;
    }

    짝[자리].파일 = 경로;
    짝[자리].방법 = '파일명';
    쓴파일.add(경로);
  }

  // ② 번호가 없는 것만 이름 자연순으로 남은 빈 자리에
  번호없는것.sort((가, 나) =>
    path.basename(가).localeCompare(path.basename(나), 'ko', { numeric: true })
  );

  let 다음빈자리 = 0;
  for (const 경로 of 번호없는것) {
    while (다음빈자리 < 짝.length && 짝[다음빈자리].파일) 다음빈자리 += 1;
    if (다음빈자리 >= 짝.length) {
      남음.push(경로);
      continue;
    }
    짝[다음빈자리].파일 = 경로;
    짝[다음빈자리].방법 = '순서';
    쓴파일.add(경로);
  }

  return 남음;
}

/** 자리별 결과를 모아 돌려준다 */
function 마무리(짝, 남음, 경고) {
  const 빈항목 = [];
  짝.forEach((하나, 자리) => {
    if (!하나.파일) 빈항목.push(자리);
  });

  if (남음.length) {
    경고.push(`짝을 짓지 못한 파일이 ${남음.length}장 있어요. 남은 파일에 뒀어요.`);
  }
  if (빈항목.length) 경고.push(`이미지가 없는 소재가 ${빈항목.length}개 있어요.`);

  return { 짝, 남은파일: 남음, 빈항목, 경고 };
}

/**
 * 전체 모드 — 처음부터 다시 배정한다.
 *
 * @param {Array<{아이템번호: string}>} 목록
 * @param {string[]} 파일경로들
 * @returns {{짝: Array, 남은파일: string[], 빈항목: number[], 경고: string[]}}
 */
function 짝짓기(목록, 파일경로들) {
  const 짝 = 목록.map((항목) => ({ 항목, 파일: null, 방법: null }));
  const 경고 = [];

  const 번호자리 = new Map();
  목록.forEach((항목, 자리) => 번호자리.set(String(항목.아이템번호).toUpperCase(), 자리));

  const 남음 = 빈자리채우기(짝, 번호자리, 파일경로들 || [], new Set());
  return 마무리(짝, 남음, 경고);
}

/**
 * 추가 모드 — 기존 짝을 지키고 새 파일만 빈 자리에 넣는다 (13-2 · 13-4).
 *
 * @param {Array<{아이템번호: string}>} 목록
 * @param {Array<{아이템번호: string, 파일: string, 방법: string}>} 기존짝
 * @param {string[]} 새파일경로들  이번에 새로 받은 것만
 */
function 추가짝짓기(목록, 기존짝, 새파일경로들) {
  const 짝 = 목록.map((항목) => ({ 항목, 파일: null, 방법: null }));
  const 경고 = [];

  const 번호자리 = new Map();
  목록.forEach((항목, 자리) => 번호자리.set(String(항목.아이템번호).toUpperCase(), 자리));

  const 쓴파일 = 기존짝앉히기(짝, 번호자리, 기존짝, 경고);
  const 남음 = 빈자리채우기(짝, 번호자리, 새파일경로들 || [], 쓴파일);
  return 마무리(짝, 남음, 경고);
}

module.exports = { 짝짓기, 추가짝짓기, 허용방법, 파일속번호 };
