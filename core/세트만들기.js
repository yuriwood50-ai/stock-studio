// ── CSV — 엑셀·구글 시트에서 한글이 깨지지 않게 UTF-8 BOM (8장) ──

function csv칸(값) {
  const 글 = String(값 ?? '');
  return /[",\r\n]/.test(글) ? '"' + 글.replace(/"/g, '""') + '"' : 글;
}

function csv쓰기(경로, 줄들) {
  const 글 = 줄들.map((줄) => 줄.map(csv칸).join(',')).join('\r\n');
  fs.writeFileSync(경로, '\ufeff' + 글 + '\r\n', 'utf8');
}

function 글쓰기(경로, 글) {
  fs.writeFileSync(경로, 글.replace(/\r?\n/g, '\r\n'), 'utf8');
}

function 폴더만들기(...조각) {
  const 경로 = path.join(...조각);
  fs.mkdirSync(경로, { recursive: true });
  return 경로;
}

function 오늘() {
  const 날 = new Date();
  const 두자리 = (수) => String(수).padStart(2, '0');
  return `${날.getFullYear()}-${두자리(날.getMonth() + 1)}-${두자리(날.getDate())}`;
}

// 같은 이름이 이미 있으면 -2, -3을 붙여 덮어쓰지 않는다 (_제외 폴더용)
function 안겹치게(폴더, 파일이름) {
  const 끝 = path.extname(파일이름);
  const 앞 = path.basename(파일이름, 끝);
  let 후보 = 파일이름;
  let 몇 = 2;
  while (fs.existsSync(path.join(폴더, 후보))) {
    후보 = `${앞}-${몇}${끝}`;
    몇 += 1;
  }
  return 후보;
}

// ── 제출 체크리스트 (8장) ──────────────────────────
// _check가 붙은 파일이 있으면 이름을 그 자리에 적는다.
// 이름이 없으면 어느 것이 표시된 파일인지 업로드준비 폴더만 봐서는 알 수 없다.

function 체크리스트글(유사이름들, 미리캔버스만이름들) {
  const 줄 = ['공통', '- [ ] _check 붙은 파일 직접 확인 — 03_이미지에서 볼 것'];

  유사이름들.forEach((하나) => 줄.push('      ' + 하나));

  줄.push(
    '- [ ] 권리 확인이 필요한 요소 없음',
    '',
    '어도비스톡  (04_업로드준비 바로 아래 파일만)',
    '- [ ] 생성형 AI 표시',
    '- [ ] 제목·키워드 작성',
    '',
    '미리캔버스  (위 파일 + 미리캔버스만 폴더)',
    '- [ ] 배경이 실제로 투명한지 (요소는 투명 PNG여야 함)',
    '- [ ] 짧은 축 700px 이상 · 긴 축 9800px 이하',
    '- [ ] 요소 이름 · 키워드 작성',
    ''
  );

  // 갈림길에서 미리캔버스 쪽으로 간 파일 (7장 10번).
  // 어느 것이 왜 갈렸는지 폴더만 봐서는 알 수 없으므로 이름을 적는다
  const 미리만 = 미리캔버스만이름들 || [];
  if (미리만.length) {
    줄.push(
      '미리캔버스만 폴더',
      ...미리만.map((하나) => '      ' + 하나),
      '',
      '이 파일들은 어도비스톡 4MP 하한에 못 미쳐요.',
      '어도비에도 올리려면 대각선 구도로 다시 그려야 해요.',
      '(가로로 누운 가늘고 긴 소재는 짧은 축이 얇아 4MP를 못 채워요.',
      ' 대각선으로 놓으면 같은 소재도 넉넉해집니다)',
      ''
    );
  }

  return 줄.join('\n');
}

/**
 * 화면에서 사람이 맞춰 준 짝을 짝짓기와 같은 모양으로 바꾼다 (6장 4번).
 * @param {Array} 항목들
 * @param {Object} 짝    아이템번호 → 파일 경로
 * @param {string[]} 이미지들  받은 파일 전부. 짝에 없는 것은 남은파일이 된다
 */
function 손으로짝지은것(항목들, 짝, 이미지들) {
  const 쓴것 = new Set();

  const 짝목록 = 항목들.map((항목) => {
    const 파일 = 짝[항목.아이템번호] || null;
    if (파일) 쓴것.add(파일);
    return { 항목, 파일, 방법: 파일 ? '사람이' : null };
  });

  const 남은파일 = 이미지들.filter((경로) => !쓴것.has(경로));
  const 빈항목 = [];
  짝목록.forEach((하나, 자리) => {
    if (!하나.파일) 빈항목.push(자리);
  });

  const 경고 = [];
  if (남은파일.length) 경고.push(`짝을 짓지 않은 파일이 ${남은파일.length}장 있어요.`);
  if (빈항목.length) 경고.push(`이미지가 없는 소재가 ${빈항목.length}개 있어요.`);

  return { 짝: 짝목록, 남은파일, 빈항목, 경고 };
}

