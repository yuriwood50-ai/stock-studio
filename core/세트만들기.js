/**
 * @param {object} 입력값
 *   입력       만들고 싶은 것 (자연어)
 *   세트번호   비우면 결과 폴더를 읽어 자동 채번
 *   세트이름   결과 폴더 이름이 된다
 *   제출유형   '투명 배경 · PNG' — 이번 범위는 이것뿐 (3장)
 *   그림체     {이름, 종류, 스타일, 금지}
 *   목록       [{소재, 형태}]
 *   이미지들   손으로 넣은 이미지 파일 경로
 * @param {object} 설정
 */
async function 만들기(입력값, 설정) {
  const 결과폴더 = path.isAbsolute(설정.결과폴더)
    ? 설정.결과폴더
    : path.join(설정모듈.작업폴더, 설정.결과폴더);

  const 제출유형 = 입력값.제출유형 || 설정모듈.오브젝트유형;
  const 그림체 = 입력값.그림체;
  const 목록 = 입력값.목록 || [];

  // 이번 범위는 오브젝트만 만든다 (3장 · 5-2장).
  // 패턴용 공통 고정 문장과 공통 금지가 없어 공통 문장 줄을 조립할 수 없다.
  if (!설정모듈.쓸수있는제출유형.includes(제출유형)) {
    throw new Error(
      `"${제출유형}"은 이번 범위에서 만들 수 없어요.\n` +
        '  패턴·배경용 공통 고정 문장과 공통 금지를 아직 쓰지 않았어요 (계획서 5-2장).\n' +
        `  지금 쓸 수 있는 건 "${설정모듈.오브젝트유형}" 하나예요.`
    );
  }

  if (!그림체) throw new Error('그림체를 찾지 못했어요.');
  if (목록.length === 0) throw new Error('소재 목록이 비어 있어요.');

  // 세트번호 — 비었으면 결과 폴더를 읽어 자동 채번 (3장)
  const 접두 = 이름.접두어(제출유형);
  let 세트번호;

  if (이름.세트번호맞나(입력값.세트번호)) {
    세트번호 = String(입력값.세트번호).trim().toUpperCase();
    if (세트번호[0] !== 접두) {
      throw new Error(
        `세트번호 ${세트번호}의 접두어가 제출 유형과 안 맞아요. ` +
          `"${제출유형}"은 ${접두}로 시작해야 해요.`
      );
    }
    if (이름.세트번호있나(결과폴더, 세트번호)) {
      throw new Error(`세트번호 ${세트번호}는 이미 있어요. 다른 번호를 넣거나 비워 두세요.`);
    }
  } else {
    세트번호 = 이름.다음세트번호(결과폴더, 접두);
  }

  const 폴더이름 = 이름.세트폴더이름(세트번호, 입력값.세트이름);
  const 세트폴더 = path.join(결과폴더, 폴더이름);

  if (fs.existsSync(세트폴더)) {
    throw new Error(`이미 있는 폴더예요: ${폴더이름}\n  세트번호를 바꾸거나 폴더를 옮기고 다시 해주세요.`);
  }

  const 정보폴더 = 폴더만들기(세트폴더, '00_세트정보');
  const 소재폴더 = 폴더만들기(세트폴더, '01_소재목록');
  const 프롬프트폴더 = 폴더만들기(세트폴더, '02_프롬프트');
  const 이미지폴더 = 폴더만들기(세트폴더, '03_이미지');
  const 제외폴더 = 폴더만들기(이미지폴더, '_제외');
  const 준비폴더 = 폴더만들기(세트폴더, '04_업로드준비');
  // 어도비 4MP에 못 미쳐 미리캔버스에만 올리는 것 (7장 10번).
  // 폴더가 나뉘어 있어야 업로드할 때 섞이지 않는다
  const 미리캔버스폴더 = 폴더만들기(준비폴더, '미리캔버스만');

  // 아이템번호는 1부터 다시 매긴다 (4장).
  // 소재명은 세트 전체를 한 번에 정리해야 중복에 -2를 붙일 수 있다 (8장)
  const 정리된소재명 = 이름.소재명들정리(목록.map((하나) => 하나.소재));

  const 항목들 = 목록.map((하나, 자리) => ({
    아이템번호: 이름.아이템번호(세트번호, 자리 + 1),
    소재: String(하나.소재 || '').trim(),
    형태: String(하나.형태 || '').trim(),
    파일소재명: 정리된소재명[자리],
  }));

  // 00_세트정보/세트.json — 이 세트를 다시 만들 수 있는 정보 전부.
  // 그림체는 세 값을 다 저장한다. 이름만 저장하면 나중에 프리셋을 고쳤을 때
  // 이 세트를 다시 조립했을 때 다른 문장이 나온다 (8장)
  글쓰기(
    path.join(정보폴더, '세트.json'),
    JSON.stringify(
      {
        세트번호,
        세트이름: String(입력값.세트이름 || '').trim(),
        입력: String(입력값.입력 || '').trim(),
        그림체: {
          이름: 그림체.이름,
          종류: 그림체.종류,
          스타일: 그림체.스타일,
          금지: 그림체.금지,
        },
        // 고정 문장은 설정에서 고칠 수 있다 (5장 · 13장). 그림체와 같은 이유로
        // 그때 쓴 문장을 통째로 남긴다 — 나중에 설정을 고쳐도 이 세트를
        // 같은 글자로 다시 조립할 수 있어야 한다 (8장)
        프롬프트문장: { ...(설정.프롬프트문장 || 설정모듈.프롬프트문장기본) },
        제출유형,
        생성조건: { ...설정.고정, 여백px: 설정.여백px, 알파임계값: 설정.알파임계값 },
        만든날: 오늘(),
      },
      null,
      2
    ) + '\n'
  );

  // 02_프롬프트/아이템번호_소재명.txt — 이미지와 같은 이름을 쓴다 (8장)
  const 프롬프트들 = 프롬프트.세트조립(항목들, 그림체, 제출유형, 설정.프롬프트문장);
  프롬프트들.forEach((글, 자리) => {
    const 항목 = 항목들[자리];
    const 파일 = `${항목.아이템번호}_${항목.파일소재명}.txt`;
    글쓰기(path.join(프롬프트폴더, 파일), 글 + '\n');
  });

  // 03_이미지 — 받은 파일을 검사하고 고쳐서 이름을 붙여 넣는다 (7장)
  //
  // 짝은 화면에서 손으로 바꿀 수 있다 (6장 4번). 바꾼 것이 오면 그대로 쓰고,
  // 안 오면 여기서 짝짓기 규칙대로 맞춘다 (build.js가 이 길로 온다).
  const 짝결과 = 입력값.짝
    ? 손으로짝지은것(항목들, 입력값.짝, 입력값.이미지들 || [])
    : 짝짓기(항목들, 입력값.이미지들 || []);
  const 줄들 = [];
  const 유사이름들 = [];

  // ① 짝지어진 파일을 한 장씩 검사한다
  const 검사결과 = [];
  for (const 하나 of 짝결과.짝) {
    if (!하나.파일) {
      검사결과.push(null);
      continue;
    }
    검사결과.push(await 검사.한장검사(하나.파일, 설정));
  }

  // ② 통과한 것끼리 닮았는지 본다. 세트 전체가 모여야 할 수 있는 일이다 (7장 9번)
  const 통과한자리 = [];
  검사결과.forEach((결과, 자리) => {
    if (결과 && 결과.통과) 통과한자리.push(자리);
  });

  const 닮음 = 유사도.닮은것찾기(
    통과한자리.map((자리) => 검사결과[자리]),
    설정.유사도기준
  );
  const 표시할자리 = new Set([...닮음.표시할자리].map((몇) => 통과한자리[몇]));

  // ③ 결과를 폴더에 담는다
  const 제외센것 = new Map();
  const 고친것센것 = new Map();
  const 고친것자세히 = new Map();
  const 미리캔버스만이름들 = [];
  let 넣은수 = 0;
  let 양쪽수 = 0;

  검사결과.forEach((결과, 자리) => {
    const 하나 = 짝결과.짝[자리];
    const 항목 = 하나.항목;

    // 아직 못 받은 줄 (8장 상태 넷 중 하나)
    if (!결과) {
      줄들.push([항목.아이템번호, 항목.소재, 항목.형태, '', '없음', 플랫폼.없음, '']);
      return;
    }

    // 제외 — 업로드준비에 담지 않고, 원본을 _제외에 원래 이름 그대로 남긴다 (7장)
    if (!결과.통과) {
      const 원래이름 = path.basename(하나.파일);
      fs.copyFileSync(하나.파일, path.join(제외폴더, 안겹치게(제외폴더, 원래이름)));
      제외센것.set(결과.사유, (제외센것.get(결과.사유) || 0) + 1);
      줄들.push([
        항목.아이템번호,
        항목.소재,
        항목.형태,
        '',
        '제외',
        플랫폼.없음,
        결과.사유,
      ]);
      return;
    }

    // 통과 — 고친 PNG를 저장한다. 확장자는 늘 .png (5-2장 고정값)
    const 유사 = 표시할자리.has(자리);
    const 이미지이름 = 이름.파일명(항목.아이템번호, 항목.파일소재명, '.png', 유사);
    fs.writeFileSync(path.join(이미지폴더, 이미지이름), 결과.버퍼);
    넣은수 += 1;

    // 갈림길 — 4MP를 넘었으면 업로드준비 바로 아래, 아니면 미리캔버스만 폴더 (7장 10번).
    // _check 파일도 업로드준비에 넣는다. 이름은 _check를 뗀 것으로 (8장)
    const 양쪽인가 = 결과.어디에 === 플랫폼.양쪽;
    const 준비이름 = 이름.유사표시뗌(이미지이름);
    const 갈곳 = 양쪽인가 ? 준비폴더 : 미리캔버스폴더;
    fs.writeFileSync(path.join(갈곳, 준비이름), 결과.버퍼);

    if (양쪽인가) 양쪽수 += 1;
    else 미리캔버스만이름들.push(path.basename(준비이름, '.png'));

    if (유사) 유사이름들.push(path.basename(준비이름, '.png'));
    결과.고친것.forEach((한줄) => {
      const 갈래 = 한줄.split(' ')[0];
      고친것센것.set(갈래, (고친것센것.get(갈래) || 0) + 1);
      // "잘라냄 1장"만으로는 얼마나 잘랐는지 알 수 없다. 실제 문구를 모아 둔다 (9장)
      if (!고친것자세히.has(갈래)) 고친것자세히.set(갈래, []);
      // 갈래 이름을 뗀 나머지. 앞에 남는 가운뎃점도 뗀다 ("sRGB · 120dpi 넣음" → "120dpi 넣음")
      고친것자세히.get(갈래).push(한줄.slice(갈래.length).replace(/^[\s·]+/, '').trim());
    });

    항목.이미지이름 = 이미지이름;
    항목.준비이름 = 준비이름;
    항목.어디에 = 결과.어디에;
    항목.점유율 = 결과.점유율;
    줄들.push([
      항목.아이템번호,
      항목.소재,
      항목.형태,
      이미지이름,
      유사 ? '표시' : '통과',
      결과.어디에,
      '',
    ]);
  });

  // 짝을 못 지은 남은 파일도 _제외에 원래 이름 그대로 (6장 6번)
  짝결과.남은파일.forEach((경로) => {
    const 원래이름 = path.basename(경로);
    fs.copyFileSync(경로, path.join(제외폴더, 안겹치게(제외폴더, 원래이름)));
  });

  if (설정.유사도기준 == null && 통과한자리.length > 1) {
    짝결과.경고.push(
      '유사도 기준이 아직 없어서 닮은 것을 표시하지 않았어요. ' +
        '아래 잰 값을 보고 설정.json의 유사도기준을 정하세요 (계획서 13장).'
    );
  }

  // 01_소재목록/목록.csv — 제외된 줄은 상태가 제외이고 옆 칸에 사유를 적는다 (8장)
  csv쓰기(path.join(소재폴더, '목록.csv'), [
    ['아이템번호', '소재', '형태·차별점', '파일명', '상태', '플랫폼', '사유'],
    ...줄들,
  ]);

  // 04_업로드준비/제목·키워드.csv — 업로드준비에 들어간 파일만, _check를 뗀 이름으로
  csv쓰기(path.join(준비폴더, '제목·키워드.csv'), [
    ['파일명', '플랫폼', '제목', '키워드'],
    ...항목들
      .filter((항목) => 항목.준비이름)
      .map((항목) => [항목.준비이름, 항목.어디에 || 플랫폼.없음, '', '']),
  ]);

  // 04_업로드준비/제출 체크리스트.md
  글쓰기(
    path.join(준비폴더, '제출 체크리스트.md'),
    체크리스트글(유사이름들, 미리캔버스만이름들)
  );

  // 미리캔버스로 간 것이 없으면 폴더가 비어 헷갈린다. 자리만 남긴다
  if (fs.readdirSync(미리캔버스폴더).length === 0) {
    글쓰기(
      path.join(미리캔버스폴더, '읽어보세요.txt'),
      '어도비스톡 4MP 하한에 못 미쳐 미리캔버스에만 올릴 파일이 여기 들어와요.\n' +
        '이번에는 모두 4MP를 넘어서 비어 있어요.\n'
    );
  }

  // 제외 폴더가 비었으면 자리만 남긴다
  if (fs.readdirSync(제외폴더).length === 0) {
    글쓰기(
      path.join(제외폴더, '읽어보세요.txt'),
      '통과 검사에서 걸린 원본과 짝을 못 지은 파일이 여기 남아요.\n' +
        '이번에는 걸린 것이 없어서 비어 있어요.\n'
    );
  }

  // 사람이 볼 점유율 — 5장 문장이 실제로 어느 정도를 만드는지 (5-2장 · 13장)
  const 점유율들 = 항목들.filter((항목) => 항목.점유율).map((항목) => 항목.점유율);

  return {
    세트번호,
    세트이름: String(입력값.세트이름 || '').trim(),
    폴더이름,
    세트폴더,
    준비폴더,
    제출유형,
    그림체이름: 그림체.이름,
    항목수: 항목들.length,
    프롬프트수: 프롬프트들.length,
    이미지수: 넣은수,
    업로드준비수: 넣은수,
    // 갈림길 결과 (7장 10번). 화면 4 요약이 이 둘을 쓴다
    양쪽수,
    미리캔버스만수: 미리캔버스만이름들.length,
    미리캔버스만이름들,
    유사표시수: 유사이름들.length,
    유사이름들,
    제외: [...제외센것].map(([까닭, 몇]) => ({ 사유: 까닭, 장수: 몇 })),
    제외수: [...제외센것.values()].reduce((합, 몇) => 합 + 몇, 0),
    // 자세히 — 한 장이면 그 문구 그대로, 여러 장이면 첫 것에 "외 N장"을 붙인다 (9장)
    고친것: [...고친것센것].map(([갈래, 몇]) => {
      const 모음 = 고친것자세히.get(갈래) || [];
      const 다른것 = [...new Set(모음)];
      let 자세히 = '';
      if (다른것.length === 1) 자세히 = 다른것[0];
      else if (다른것.length > 1) 자세히 = `${다른것[0]} 외 ${다른것.length - 1}가지`;
      return { 갈래, 장수: 몇, 자세히 };
    }),
    점유율: 점유율들.length
      ? {
          가장작은것: Math.min(...점유율들),
          가장큰것: Math.max(...점유율들),
          평균: 점유율들.reduce((합, 값) => 합 + 값, 0) / 점유율들.length,
        }
      : null,
    유사도잰것: 유사도.차이요약(닮음.잰것),
    유사도기준: 설정.유사도기준,
    // 기준값을 눈으로 정할 때 쓰는 가장 닮은 쌍들 (13장)
    닮은쌍맛보기: 닮음.잰것
      .slice()
      .sort((가, 나) => 가.차이 - 나.차이)
      .slice(0, 3)
      .map((하나) => ({
        차이: 하나.차이,
        가: 항목들[통과한자리[하나.가]].소재,
        나: 항목들[통과한자리[하나.나]].소재,
      })),
    남은파일: 짝결과.남은파일,
    빈항목수: 짝결과.빈항목.length,
    경고: 짝결과.경고,
  };
}

module.exports = { 만들기, csv쓰기, 글쓰기, 체크리스트글 };
