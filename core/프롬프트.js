// 프롬프트 조립 (계획서 5장)
//
// 여섯 줄로 조립한다. 한 세트 안에서 바뀌는 것은 2·3줄뿐이고, 나머지는 세트 내내 글자 그대로 같다.
//
// 코드북 v2 기본01·기본02는 일곱 줄이었다. 6줄 용도(Commercial stock asset ...)는
// 그림 지시가 아니라 용도 메모라 뺐다 — 모델이 그걸 읽고 할 수 있는 일은
// 그림을 범용 클립아트 쪽으로 당기는 것뿐이었다 (0장 개정표).
//
// 픽셀 값(크기 · dpi · 색공간 · 용량)은 여기 넣지 않는다. 프롬프트에 적는다고
// 보장되지 않기 때문이다. 투명 처리는 6장 파일받기 문구가, 크기와 여백은
// 7장 통과 검사가 맡는다.

const { 패턴유형, 프롬프트문장기본 } = require('./설정');

// ── 공통 고정 문장 (5장 4줄 뒤 · 5줄 · 6줄 앞) ─────
//
// 늘 같다. 한 세트 안에서 바뀌는 것은 2·3줄뿐이다.
//
// **문장 자체는 설정.json의 `프롬프트문장`에 있다.** 13장이 "이 영어 문장은
// ChatGPT에 넣어본 적이 없다. 첫 세트에서 확인한다"고 적어 뒀다. 고칠 것이
// 예정된 값이라 코드가 아니라 설정에 뒀다. 여기 있는 것은 설정을 못 받았을 때의 기본값이다.
//
// 앞 판 구성에 있던 filling most of the canvas 는 새 문장에 없다. 점유율이
// 75% 아래로 내려가면 `미리캔버스만`이 늘어난다. 첫 세트에서 잰다 (5-2장).
const 오브젝트구성 = 프롬프트문장기본.구성;
const 오브젝트품질 = 프롬프트문장기본.품질;
const 공통금지 = 프롬프트문장기본.공통금지;

// ── 틀 ─────────────────────────────────────────────

// 문장 세 개(구성 · 품질 · 공통금지)를 받아 오브젝트 틀을 만든다. 안 주면 기본값으로 간다
function 오브젝트틀만들기(문장) {
  const 쓸것 = { ...프롬프트문장기본, ...(문장 || {}) };
  return {
    첫줄: (종류) => `Create one isolated ${종류} illustration of a single object.`,
    소재이름: 'Subject',
    품질: 쓸것.품질, // 4줄 그림체 스타일 뒤에 붙는다
    구성: 쓸것.구성,
    공통금지: 쓸것.공통금지, // 오브젝트에만 붙는다
  };
}

// 패턴 — 이번 범위에서는 쓰지 않는다 (3장에서 JPG를 막았다).
// 장면용 공통 고정 문장과 공통 금지를 아직 쓰지 않아 공통금지가 비어 있다.
// 설정으로 빼지 않은 것도 그 때문이다. 다음 범위에서 같이 정한다.
const 패턴틀 = {
  첫줄: (종류) => `Create a high-resolution square ${종류} pattern background.`,
  소재이름: 'Pattern theme',
  구성:
    'Composition: repeatable all-over pattern, balanced spacing, ' +
    'no single large focal object, no text, no logo, no watermark.',
  용도:
    'Designed for backgrounds, wrapping paper, cards, labels, newsletters, ' +
    'and social media templates.',
  공통금지: '',
};

// ── 잔손질 (5장) ───────────────────────────────────

// 여러 줄로 적힌 값을 한 줄로. 앞뒤 공백은 뗀다
function 한줄로(문장) {
  return String(문장 || '').replace(/\s+/g, ' ').trim();
}

// 값 끝의 마침표는 떼어 둔다. 마침표는 조립할 때 붙인다
function 마침표뗌(문장) {
  return 한줄로(문장).replace(/[.\s]+$/, '');
}

/**
 * 4줄을 만든다. 그림체 스타일 뒤에 공통 품질 문장을 잇는다.
 * 품질이 비면 스타일만 남는다.
 */
function 화풍줄(스타일, 품질) {
  const 조각 = [마침표뗌(스타일), 마침표뗌(품질)].filter(Boolean);
  return `Art direction: ${조각.map((하나) => 하나 + '.').join(' ')}`;
}

/**
 * 6줄을 만든다.
 * 공통 금지와 그림체 금지를 쉼표로 잇되, 그림체 금지가 비면 쉼표도 뺀다.
 * 안 그러면 `... fringing, .` 이 된다.
 */
function 금지줄(공통, 그림체금지) {
  const 조각 = [마침표뗌(공통), 마침표뗌(그림체금지)].filter(Boolean);
  return 조각.length ? `Avoid ${조각.join(', ')}.` : '';
}

/**
 * 소재 하나의 프롬프트를 조립한다.
 * @param {{소재: string, 형태: string}} 항목
 * @param {{종류: string, 스타일: string, 금지: string}} 그림체
 * @param {string} 제출유형
 * @param {{구성?: string, 품질?: string, 공통금지?: string}} [문장]  설정.프롬프트문장
 * @returns {string} 여섯 줄
 */
function 조립(항목, 그림체, 제출유형, 문장) {
  const 틀 = 제출유형 === 패턴유형 ? 패턴틀 : 오브젝트틀만들기(문장);
  const 종류 = 한줄로(그림체.종류) || 'hand-drawn';

  return [
    틀.첫줄(종류),
    `${틀.소재이름}: ${한줄로(항목.소재)}`,
    `Form: ${한줄로(항목.형태)}`,
    화풍줄(그림체.스타일, 틀.품질),
    틀.구성,
    틀.용도, // 패턴틀에만 있다. 오브젝트에는 이 줄이 없다
    금지줄(틀.공통금지, 그림체.금지),
  ]
    .filter(Boolean)
    .join('\n');
}

function 세트조립(목록, 그림체, 제출유형, 문장) {
  return 목록.map((항목) => 조립(항목, 그림체, 제출유형, 문장));
}

// ── 화면 1 미리보기 (3장) ──────────────────────────
//
// 여섯 줄 전체를 보여주되 2·3줄은 {소재} {형태} 그대로 둔다.
// 소재마다 달라지는 자리라서 화면 1에서는 채울 값이 없다.

const 소재자리 = '{소재}';
const 형태자리 = '{형태}';

// 5장 "무엇이 어디서 오나" 표를 그대로 옮긴 것
const 줄출처 = [
  { 이름: '그림체', 바뀜: '세트마다' },
  { 이름: '목록', 바뀜: '소재마다' },
  { 이름: '목록', 바뀜: '소재마다' },
  { 이름: '그림체 + 공통', 바뀜: '세트마다' },
  { 이름: '공통', 바뀜: '안 바뀜' },
  { 이름: '공통 + 그림체', 바뀜: '세트마다' },
];

function 미리보기(그림체, 제출유형, 문장) {
  const 줄들 = 조립(
    { 소재: 소재자리, 형태: 형태자리 },
    그림체,
    제출유형,
    문장
  ).split('\n');

  return 줄들.map((글, 자리) => ({
    번호: 자리 + 1,
    글,
    출처: 줄출처[자리] ? 줄출처[자리].이름 : '공통',
    바뀜: 줄출처[자리] ? 줄출처[자리].바뀜 : '안 바뀜',
    소재줄: 자리 === 1 || 자리 === 2,
  }));
}

module.exports = {
  조립,
  세트조립,
  미리보기,
  소재자리,
  형태자리,
  공통금지,
  오브젝트구성,
  오브젝트품질,
  한줄로,
  마침표뗌,
  화풍줄,
  금지줄,
};
